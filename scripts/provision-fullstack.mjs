/**
 * Provision EnergyMonitor for Neon/Supabase/Vercel Postgres + production secrets.
 *
 * Usage:
 *   node scripts/provision-fullstack.mjs --database-url "postgresql://..." --direct-url "postgresql://..."
 *   node scripts/provision-fullstack.mjs --from-neon-connection-string "postgresql://...@ep-xxx.neon.tech/neondb?sslmode=require"
 *
 * Then:
 *   npm run db:push
 *   npm run db:seed
 *   npx vercel env pull   (after setting vars in Vercel)
 */
import { randomBytes } from "node:crypto";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

function arg(name, fallback = "") {
  const idx = process.argv.indexOf(`--${name}`);
  if (idx === -1) return fallback;
  return process.argv[idx + 1] ?? fallback;
}

function secret(bytes = 32) {
  return randomBytes(bytes).toString("base64url");
}

function toPooledAndDirect(connectionString) {
  // Neon: pooled host often contains -pooler; direct does not.
  const url = new URL(connectionString);
  const direct = connectionString;
  let pooled = connectionString;
  if (!url.hostname.includes("-pooler") && url.hostname.includes("neon.tech")) {
    const pooledHost = url.hostname.replace(".neon.tech", "-pooler.neon.tech");
    // Neon pooler host pattern: ep-xxx-pooler.region.aws.neon.tech
    const parts = url.hostname.split(".");
    if (parts[0] && !parts[0].endsWith("-pooler")) {
      parts[0] = `${parts[0]}-pooler`;
      url.hostname = parts.join(".");
      url.searchParams.set("sslmode", "require");
      // Prisma + serverless
      if (!url.searchParams.has("pgbouncer")) url.searchParams.set("pgbouncer", "true");
      if (!url.searchParams.has("connection_limit")) url.searchParams.set("connection_limit", "1");
      pooled = url.toString();
    }
  } else {
    const u = new URL(connectionString);
    if (!u.searchParams.has("sslmode")) u.searchParams.set("sslmode", "require");
    if (!u.searchParams.has("pgbouncer")) u.searchParams.set("pgbouncer", "true");
    if (!u.searchParams.has("connection_limit")) u.searchParams.set("connection_limit", "1");
    pooled = u.toString();
  }
  return { pooled, direct };
}

const neonSingle = arg("from-neon-connection-string");
let databaseUrl = arg("database-url");
let directUrl = arg("direct-url");
const appUrl = arg("app-url", "http://localhost:3000");
const writeEnv = !process.argv.includes("--no-write");
const runPush = process.argv.includes("--push");
const runSeed = process.argv.includes("--seed");

if (neonSingle) {
  const pair = toPooledAndDirect(neonSingle);
  databaseUrl = pair.pooled;
  directUrl = pair.direct;
}

if (!databaseUrl || !directUrl) {
  console.error(`Missing database URLs.

Create a Neon project at https://console.neon.tech
Copy the connection string, then run:

  npm run db:provision -- --from-neon-connection-string "postgresql://USER:PASS@ep-xxx.us-east-2.aws.neon.tech/neondb?sslmode=require" --push --seed

Or pass both:

  npm run db:provision -- --database-url "postgresql://...pooler..." --direct-url "postgresql://...direct..." --push --seed
`);
  process.exit(1);
}

const authSecret = secret(32);
const cronSecret = secret(24);
const credKey = secret(32);

const envBody = `# Generated by scripts/provision-fullstack.mjs — DO NOT COMMIT
# Managed Postgres (Neon / Supabase / Vercel Postgres)

DATABASE_URL="${databaseUrl}"
DIRECT_URL="${directUrl}"

AUTH_SECRET="${authSecret}"
APP_URL="${appUrl}"
NODE_ENV="production"
ALLOW_SIMULATED_TELEMETRY="false"
CRON_SECRET="${cronSecret}"
CREDENTIALS_ENCRYPTION_KEY="${credKey}"
LIVE_POLL_INTERVAL_MS="8000"
STALE_AFTER_SECONDS="120"
MQTT_BRIDGE_ENABLED="false"
`;

const vercelEnvLines = [
  `DATABASE_URL=${databaseUrl}`,
  `DIRECT_URL=${directUrl}`,
  `AUTH_SECRET=${authSecret}`,
  `APP_URL=${appUrl}`,
  `NODE_ENV=production`,
  `ALLOW_SIMULATED_TELEMETRY=false`,
  `CRON_SECRET=${cronSecret}`,
  `CREDENTIALS_ENCRYPTION_KEY=${credKey}`,
  `LIVE_POLL_INTERVAL_MS=8000`,
  `STALE_AFTER_SECONDS=120`,
].join("\n");

if (writeEnv) {
  const prodLocal = path.join(root, ".env.production.local");
  writeFileSync(prodLocal, envBody, "utf8");
  console.log(`Wrote ${prodLocal}`);

  // Also write a copy for local testing against remote DB (optional)
  const remoteLocal = path.join(root, ".env.remote");
  writeFileSync(
    remoteLocal,
    envBody.replace('NODE_ENV="production"', 'NODE_ENV="development"').replace(
      'ALLOW_SIMULATED_TELEMETRY="false"',
      'ALLOW_SIMULATED_TELEMETRY="true"',
    ),
    "utf8",
  );
  console.log(`Wrote ${remoteLocal} (dev against remote DB; simulated telemetry allowed)`);

  const vercelFile = path.join(root, ".vercel-env-production.txt");
  writeFileSync(vercelFile, vercelEnvLines + "\n", "utf8");
  console.log(`Wrote ${vercelFile} — paste into Vercel → Settings → Environment Variables (or use vercel env add)`);
}

const envForChild = {
  ...process.env,
  DATABASE_URL: databaseUrl,
  DIRECT_URL: directUrl,
  AUTH_SECRET: authSecret,
  APP_URL: appUrl,
  NODE_ENV: "development",
  ALLOW_SIMULATED_TELEMETRY: "true",
  CRON_SECRET: cronSecret,
  CREDENTIALS_ENCRYPTION_KEY: credKey,
};

if (runPush) {
  console.log("Running prisma db push...");
  const r = spawnSync("npx", ["prisma", "db", "push", "--accept-data-loss"], {
    cwd: root,
    env: envForChild,
    stdio: "inherit",
    shell: true,
  });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

if (runSeed) {
  console.log("Running prisma db seed...");
  const r = spawnSync("npm", ["run", "db:seed"], {
    cwd: root,
    env: envForChild,
    stdio: "inherit",
    shell: true,
  });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

console.log(`
Full-stack Postgres ready.

Next:
  1) Open Vercel → Project → Settings → Environment Variables
     Import values from .vercel-env-production.txt (set APP_URL to your vercel URL)
  2) Deploy: npx vercel --prod
  3) ESP secrets.h APP_BASE_URL = your https://….vercel.app
  4) Login: owner@example.com / ChangeMeNow1!  (change password after first login)
`);
